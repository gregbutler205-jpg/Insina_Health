// ── 5. One button, one gate (source pins) ────────────────────────────────────
{
  const btn = readFileSync(SRC("components/PrintButton.jsx"), "utf8");
  ok(btn.includes('import { requestReport } from "../rie/preflightChecks.js"') && btn.includes("requestReport(type"), "PrintButton runs every print through the RIE preflight (DEC-061 C)");
  const tabs = readdirSync(SRC("components/tabs")).filter(f => f.endsWith(".jsx"));
  const read = (f) => readFileSync(SRC("components/tabs/" + f), "utf8");
  const users = tabs.filter(f => read(f).includes("<PrintButton"));
  const expected = ["Tab02.jsx", "Tab04.jsx", "Tab05.jsx", "Tab06.jsx", "Tab09.jsx", "Tab10.jsx", "Tab12.jsx", "Tab14.jsx", "Tab15.jsx", "Tab16.jsx", "Tab17.jsx"];
  ok(expected.every(f => users.includes(f)), `every printing screen uses the shared PrintButton (got ${users.join(", ")})`);
  // Tab13's consent reprint keeps its own button: the consent record is outside DEC-061 by design.
  ok(!tabs.filter(f => f !== "Tab13.jsx").some(f => /<PrintLabel/.test(read(f))), "no screen (other than the consent reprint) renders the old PrintLabel button any more");
  const types = new Set();
  for (const f of tabs) for (const m of read(f).matchAll(/reportType[:=]\s*"([a-zA-Z]+)"/g)) types.add(m[1]);
  const reports = readFileSync(SRC("components/dashboard/ReportsPage.jsx"), "utf8");
  for (const m of reports.matchAll(/requestReport\("([a-zA-Z]+)"/g)) types.add(m[1]);
  const labelsSrc = readFileSync(SRC("rie/preflightChecks.js"), "utf8");
  const labels = labelsSrc.slice(labelsSrc.indexOf("export const REPORT_LABELS"), labelsSrc.indexOf("};", labelsSrc.indexOf("export const REPORT_LABELS")));
  const missing = [...types].filter(t => !new RegExp(`\\b${t}:`).test(labels));
  ok(types.size >= 10 && missing.length === 0, `every report type has a preflight label (${[...types].sort().join(", ")}${missing.length ? "; missing " + missing.join(", ") : ""})`);
  ok((reports.match(/requestReport\(/g) || []).length === 4 && reports.includes('requestReport("profile", () => printProfile())') && reports.includes('requestReport("edPrep", () => printEmergency())') && reports.includes('requestReport("labs", () => printLabReport(readLabs()))'),
     "Reports: the four prints are gated; the profile prints in one step with every card (DEC-060); the Emergency Card runs the ED Prep checklist; the Lab Report prints from the record");
}

